package inoueai

import (
	"context"
	"net/http"
	"strings"
)

// WithBearerToken returns a ClientOption that attaches a JWT bearer access
// token to every request via the Authorization header. It is a thin, stable
// convenience over the generated WithRequestEditorFn so callers do not have to
// hand-write the editor closure for the common case.
//
// The token is the access token returned by /v1/auth/login (HS256 JWT; see
// ADR-0009). An empty token is a no-op editor — the request is sent without an
// Authorization header, which the server rejects with 401 for protected
// operations.
//
// This file is hand-written and is NOT regenerated by `make sdk`.
func WithBearerToken(token string) ClientOption {
	return WithRequestEditorFn(func(_ context.Context, req *http.Request) error {
		if strings.TrimSpace(token) == "" {
			return nil
		}
		req.Header.Set("Authorization", "Bearer "+token)
		return nil
	})
}
